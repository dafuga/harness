import { consoleServerDirectory, type HostFile } from './consoleHostFiles';

export interface IndexFile {
	/** Path inside the history index: `index.json`, `revisions/<commit>.json` or `media/<name>`. */
	path: string;
	bytes: Uint8Array;
}

const types: Record<string, string> = {
	png: 'image/png',
	jpg: 'image/jpeg',
	jpeg: 'image/jpeg',
	webp: 'image/webp',
	gif: 'image/gif',
	wav: 'audio/wav',
	mp3: 'audio/mpeg',
	m4a: 'audio/mp4',
	ogg: 'audio/ogg',
	mp4: 'video/mp4',
	webm: 'video/webm',
	json: 'application/json',
	txt: 'text/plain'
};
const data = /^(index\.json|revisions\/[0-9a-f]{40}\.json)$/;
const media = /^media\/([0-9a-f]{64}\.([a-z0-9]+))$/;
const header = '// Generated by `harness console install` from a history index. Do not edit.\n';

/**
 * Turns the files of a history index into modules of the host's server bundle: JSON as text,
 * media as base64 with its type. Anything that is not part of an index is left out.
 */
export function consoleDataModules(files: IndexFile[]): HostFile[] {
	return files.flatMap((file) => {
		if (data.test(file.path)) {
			const text = Buffer.from(file.bytes).toString('utf8');
			const contents = `${header}export default ${JSON.stringify(text)};\n`;
			return [{ path: `${consoleServerDirectory}/data/${file.path}.ts`, contents }];
		}
		const named = media.exec(file.path);
		if (!named) return [];
		const type = types[named[2]] ?? 'application/octet-stream';
		const encoded = Buffer.from(file.bytes).toString('base64');
		const contents = `${header}export const type = ${JSON.stringify(type)};\nexport default ${JSON.stringify(encoded)};\n`;
		return [{ path: `${consoleServerDirectory}/data/media/${named[1]}.ts`, contents }];
	});
}
