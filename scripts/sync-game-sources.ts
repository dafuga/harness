import { format } from 'prettier';
import { exampleDocument } from '../packages/game/src/utils/keyDoor';
import { readFile, writeFile } from 'node:fs/promises';
const paths = [
	'models/Game.types.ts',
	'validators/gameDocument.ts',
	'utils/gameStep.ts',
	'utils/keyDoor.ts',
	'utils/checkpointGraph.ts',
	'adapters/Canvas2dAdapter.ts',
	'adapters/ThreeSceneAdapter.ts',
	'adapters/Software3dAdapter.ts',
	'adapters/DecartStreamAdapter.ts'
];
const sources: Record<string, string> = {};
for (const path of paths) sources[path] = await readFile('packages/game/src/' + path, 'utf8');
await writeFile(
	'src/templates/gameSources.ts',
	'// Generated by scripts/sync-game-sources.ts; checked against engine sources in tests.\nexport const gameSources: Record<string,string> = ' +
		JSON.stringify(sources, null, '\t') +
		';\n'
);

for (const dimension of ['2d', '3d'] as const) {
	const text = await format(JSON.stringify(exampleDocument(dimension)), {
		parser: 'json',
		useTabs: true,
		printWidth: 100
	});
	await writeFile(
		'src/templates/gameDocument' + dimension + '.ts',
		'export const gameDocument' + dimension + ' = ' + JSON.stringify(text) + ';\n'
	);
}
