import { readFile, writeFile } from 'node:fs/promises';
import { posix } from 'node:path';
import { format } from 'prettier';
import { formatConfigFiles } from '../src/templates/development-tooling/formatConfig';

/** Generated games keep their src/lib/game layout; each destination names its engine source. */
export const gameSourceLayout: Readonly<Record<string, string>> = {
	'models/Game.types.ts': 'models/game-authoring/Game.types.ts',
	'validators/LevelValidator.ts': 'validators/game-authoring/LevelValidator.ts',
	'validators/gameDocument.ts': 'validators/game-authoring/gameDocument.ts',
	'validators/gameDocument.types.ts': 'validators/game-authoring/gameDocument.types.ts',
	'utils/gameStep.ts': 'utils/game-authoring/gameStep.ts',
	'utils/keyDoor.ts': 'utils/game-authoring/keyDoor.ts',
	'utils/checkpointGraph.ts': 'utils/game-authoring/checkpointGraph.ts',
	'adapters/Canvas2dAdapter.ts': 'adapters/game-authoring/Canvas2dAdapter.ts',
	'adapters/ThreeSceneAdapter.ts': 'adapters/game-authoring/ThreeSceneAdapter.ts',
	'adapters/Software3dAdapter.ts': 'adapters/game-authoring/Software3dAdapter.ts',
	'adapters/Software3dAdapter.types.ts': 'adapters/game-authoring/Software3dAdapter.types.ts',
	'adapters/DecartStreamAdapter.ts': 'adapters/agents-providers/DecartStreamAdapter.ts',
	'adapters/DecartStreamAdapter.types.ts': 'adapters/agents-providers/DecartStreamAdapter.types.ts'
};

/** The formatting a generated project checks, so embedded sources pass its own format check. */
const generatedStyle = JSON.parse(
	formatConfigFiles().find((file) => file.path === '.prettierrc')!.contents
);

/** An engine source as embedded at its destination: only relative module specifiers change. */
export async function embeddedSource(destination: string, text: string): Promise<string> {
	const source = gameSourceLayout[destination];
	const destinations = Object.keys(gameSourceLayout);
	const relocated = text.replace(
		/(\bfrom\s+|\bimport\s*\(\s*)'(\.{1,2}\/[^']+)'/g,
		(_whole, lead: string, specifier: string) => {
			const target = posix.join(posix.dirname(source), specifier) + '.ts';
			const embedded = destinations.find((path) => gameSourceLayout[path] === target);
			if (!embedded) throw new Error(`${source} imports ${specifier}, which is not embedded.`);
			const moved = posix.relative(posix.dirname(destination), embedded).replace(/\.ts$/, '');
			return `${lead}'${moved.startsWith('.') ? moved : './' + moved}'`;
		}
	);
	return format(relocated, { ...generatedStyle, parser: 'typescript' });
}

if (import.meta.main) {
	const sources: Record<string, string> = {};
	for (const [destination, source] of Object.entries(gameSourceLayout))
		sources[destination] = await embeddedSource(
			destination,
			await readFile('packages/game/src/' + source, 'utf8')
		);
	await writeFile(
		'src/templates/game-authoring/gameSources.ts',
		'// Generated by scripts/sync-game-sources.ts; checked against engine sources in tests.\nexport const gameSources: Record<string,string> = ' +
			JSON.stringify(sources, null, '\t') +
			';\n'
	);
}
