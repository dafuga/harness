import { test } from 'vitest';
import { expect } from '../verificationExpect';
import { recordExampleCases } from '../support/recordExampleCases';
import {
	consoleDataModules,
	bundledSize
} from '../../src/cli/program/console-install-service/consoleDataModules';
import type {
	IndexFile,
	BundledSize
} from '../../src/utils/development-tooling/consoleDataModules';

const state = 'generates-recognized-data-modules-and-sizes-the-bundle';
const header = '// Generated by `harness console install` from a history index. Do not edit.\n';

test('Generates recognized data modules and sizes the bundle', () => {
	const jsonBytes = new TextEncoder().encode('{"version":1}');
	const pngBytes = Uint8Array.from(
		Buffer.from(
			'iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+nmf8AAAAASUVORK5CYII=',
			'base64'
		)
	);
	const files: IndexFile[] = [
		{ path: 'index.json', bytes: jsonBytes },
		{ path: `media/${'a'.repeat(64)}.png`, bytes: pngBytes },
		{ path: `media/${'b'.repeat(64)}.xyz`, bytes: Uint8Array.from([1, 2]) },
		{ path: 'notes/private.json', bytes: jsonBytes }
	];
	const modules = consoleDataModules(files);
	const summary = modules.map(({ path, contents }) => ({ path, contents }));
	expect(summary).toHaveLength(3);
	expect(summary[0]).toEqual({
		path: 'src/lib/server/harness/data/index.json.ts',
		contents: `${header}export default "{\\"version\\":1}";\n`
	});
	expect(summary[1]?.contents).toContain('export const type = "image/png";');
	expect(summary[2]?.contents).toContain('application/octet-stream');
	const emptySize = bundledSize([]);
	const size = bundledSize(modules) satisfies BundledSize | null;
	expect(emptySize).toBeNull();
	expect(size).toMatchObject({
		files: 3,
		bytes: modules.reduce((total, file) => total + file.contents.length, 0)
	});
	recordExampleCases(
		{
			unitId: 'function.console-data-modules',
			symbol: 'consoleDataModules',
			state,
			evidence: 'examples-cases',
			file: `${state}.json`
		},
		[
			{
				name: 'index JSON, PNG, unknown media type, and unrelated file',
				input: files,
				output: summary
			}
		]
	);
	recordExampleCases(
		{
			unitId: 'function.console-data-modules',
			symbol: 'bundledSize',
			state,
			evidence: 'examples-cases',
			file: `${state}.json`
		},
		[
			{ name: 'no modules', input: [], output: emptySize },
			{ name: 'generated modules', input: summary, output: size }
		]
	);
});
