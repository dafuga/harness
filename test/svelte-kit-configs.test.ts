import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { cp, mkdtemp, symlink } from 'node:fs/promises';
import { join, relative, resolve } from 'node:path';
import { afterEach, expect, test } from 'vitest';
import { unsyncedKitPackages } from './svelteKitConfigs';
import { runCommand } from './support/cli';

/**
 * Before root tests are collected, the SvelteKit packages whose generated config is missing are
 * found from their own tsconfig.json: a package that extends `./.svelte-kit/tsconfig.json`
 * without having it, and no other.
 */
const roots: string[] = [];
afterEach(() => roots.splice(0).forEach((root) => rmSync(root, { recursive: true, force: true })));
function tree(packages: Record<string, { tsconfig?: string; generated?: boolean }>): string {
	const root = mkdtempSync(join(tmpdir(), 'harness-kit-configs-'));
	roots.push(root);
	for (const [name, { tsconfig, generated }] of Object.entries(packages)) {
		const directory = join(root, 'packages', name);
		mkdirSync(join(directory, '.svelte-kit'), { recursive: true });
		if (tsconfig !== undefined) writeFileSync(join(directory, 'tsconfig.json'), tsconfig);
		if (generated) writeFileSync(join(directory, '.svelte-kit', 'tsconfig.json'), '{}');
	}
	return root;
}
const kit =
	'{\n\t"extends": "./.svelte-kit/tsconfig.json",\n\t"compilerOptions": { "strict": true }\n}\n';

test('a package extending the generated SvelteKit config without it is found, and only that one', async () => {
	const root = tree({
		hub: { tsconfig: kit },
		reports: { tsconfig: `// generated by svelte-kit\n${kit}` },
		desktop: { tsconfig: kit, generated: true },
		planning: { tsconfig: '{ "compilerOptions": { "strict": true } }' },
		collaboration: {}
	});
	expect(unsyncedKitPackages(root)).toEqual(['hub', 'reports']);
	await assertFreshCliStartup();
}, 30_000);

/** Root setup may sync apps for tests; standalone CLI startup must never depend on that sync. */
async function assertFreshCliStartup(): Promise<void> {
	const source = resolve(import.meta.dirname, '..');
	const fresh = await mkdtemp(join(tmpdir(), 'harness-cli-unsynced-'));
	roots.push(fresh);
	const generated =
		/(?:^|\/)(?:\.git|node_modules|\.svelte-kit|\.cache|\.wrangler|test-results|playwright-report)(?:\/|$)|^(?:dist|target|work|coverage)(?:\/|$)|^packages\/[^/]+\/build(?:\/|$)/;
	await cp(source, fresh, {
		recursive: true,
		verbatimSymlinks: true,
		filter: (path) => !generated.test(relative(source, path))
	});
	await symlink(join(source, 'node_modules'), join(fresh, 'node_modules'), 'dir');
	expect(unsyncedKitPackages(fresh)).toContain('desktop');
	for (const args of [
		['units', '--help'],
		['info', 'units', '--json']
	]) {
		const started = await runCommand(['bun', 'src/index.ts', ...args], fresh, false);
		expect(started.exitCode, `Fresh CLI must start before SvelteKit sync:\n${started.stderr}`).toBe(
			0
		);
		expect(started.stdout).toContain('check-contract');
	}
	expect(unsyncedKitPackages(fresh)).toContain('desktop');
}

test('once every generated config exists, nothing is left to sync', () => {
	const root = tree({
		hub: { tsconfig: kit, generated: true },
		reports: { tsconfig: kit, generated: true }
	});
	expect(unsyncedKitPackages(root)).toEqual([]);
});
