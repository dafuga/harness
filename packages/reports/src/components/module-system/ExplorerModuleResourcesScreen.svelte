<script lang="ts">
	import type { ExplorerLocation } from '../../models/explorer-ui/Explorer.types';
	import type { ExplorerScreenProps } from '../../models/explorer-ui/ExplorerScreen.types';
	import type {
		ModuleEntry,
		ModuleResource
	} from '../../../../../src/services/module-system/moduleDefinition.types';
	import { plainClick } from '../../utils/explorer-ui/harnessShell';
	import ExplorerFrame from '../explorer-ui/ExplorerFrame.svelte';
	let host: ExplorerScreenProps = $props();
	// `<module id>.<resource id>`: neither id can hold a dot, so one split names both.
	let ids = $derived((host.route.entity ?? '').split('.'));
	// Only the shown revision's own catalog: nothing is read from the working copy or another commit.
	let catalog = $derived(host.head.modules);
	let entry = $derived(
		ids.length === 2 ? catalog?.modules.find((item) => item.definition.id === ids[0]) : undefined
	);
	let resource = $derived(entry?.definition.resources.find((item) => item.id === ids[1]));
	/** A module screen at the shown branch and commit; no helper, section or tab is carried over. */
	function at(screen: ExplorerLocation['screen'], entity?: string): ExplorerLocation {
		const { branch, commit } = host.route;
		return { branch, commit, category: 'pages', screen, ...(entity ? { entity } : {}) };
	}
	// A modified click, or another button, stays the browser's so a new tab can open it.
	function follow(event: MouseEvent, to: ExplorerLocation) {
		if (!plainClick(event)) return;
		event.preventDefault();
		host.onroute(to);
	}
	/** What this revision's state file records for the type: nothing is generated or guessed. */
	function made(found: ModuleEntry, kind: ModuleResource) {
		const { id } = found.definition;
		return found.instances.filter((item) => item.module === id && item.type === kind.id);
	}
	/** Why no resources are listed, in this revision's own terms. */
	function absence(): string {
		if (!catalog) return 'No module catalog was indexed for this revision.';
		if (!host.route.entity) return 'No resource type is named in this address.';
		return `No module declares the resource type “${host.route.entity}” at this revision.`;
	}
</script>

{#snippet link(to: ExplorerLocation, text: string)}
	<hx-a href={host.lens.href(to)} onclick={(event) => follow(event, to)}>{text}</hx-a>
{/snippet}

<!-- A command is copied into a terminal: this page installs and generates nothing itself. -->
{#snippet command(label: string, text: string)}
	<hx-figure class="res-command">
		<hx-figcaption>{label}</hx-figcaption>
		<hx-pre><hx-code>{text}</hx-code></hx-pre>
	</hx-figure>
{/snippet}

<!-- Instructions and names are shown as text; no manifest content is read as markup or run. -->
{#snippet listing(found: ModuleEntry, kind: ModuleResource)}
	{@const id = found.definition.id}
	{@const listed = made(found, kind)}
	<hx-h1 id="res-title">{kind.title}</hx-h1>
	<hx-p class="ex-lead">
		Generated by the {@render link(at('modules', id), found.definition.title)} module.
	</hx-p>
	{@render command('Generate', `harness module generate ${id} ${kind.id} Example`)}
	<hx-ul class="ex-reasons res-text">
		{#each kind.instructions as line, position (position)}<hx-li>{line}</hx-li>{/each}
	</hx-ul>
	<hx-h2 id="res-made">Generated <hx-span class="ex-pill">{listed.length}</hx-span></hx-h2>
	{#if listed.length}
		<hx-ul class="res-list" aria-labelledby="res-made">
			{#each listed as item, position (position)}
				<hx-li class="ex-card">
					<hx-h3>{item.name}</hx-h3>
					<hx-ul class="res-text" aria-label={`${item.name} source files`}>
						{#each item.files as file, index (index)}<hx-li><hx-code>{file}</hx-code></hx-li>{/each}
					</hx-ul>
				</hx-li>
			{/each}
		</hx-ul>
	{:else}
		<hx-p class="ex-empty">Nothing generated yet. Run the command above to add one.</hx-p>
	{/if}
{/snippet}

<!-- Generation needs the module installed, so the type is unavailable until it is. -->
{#snippet unavailable(found: ModuleEntry, kind: ModuleResource)}
	<hx-h1 id="res-title">{kind.title}</hx-h1>
	<hx-p class="ex-empty">
		Unavailable: {found.definition.title} is not installed at this revision.
	</hx-p>
	{@render command('Install', `harness module add ${found.definition.id}`)}
{/snippet}

<!-- Generated resources are read from the selected revision, with or without a unit registry. -->
<ExplorerFrame {host} registryRequired={false}>
	{#snippet children()}
		<hx-section
			class="ex-index"
			aria-labelledby="res-title"
			data-harness-component="explorer-module-resources-screen"
		>
			<hx-nav class="ex-crumbs" aria-label="Breadcrumb">
				<hx-ol>
					<hx-li>{@render link(at('modules'), 'Modules')}</hx-li>
					{#if entry}
						{@const owner = at('modules', entry.definition.id)}
						<hx-li>{@render link(owner, entry.definition.title)}</hx-li>
					{/if}
					<hx-li aria-current="page">{resource?.title ?? 'Not found'}</hx-li>
				</hx-ol>
			</hx-nav>
			{#if entry?.installed && resource}
				{@render listing(entry, resource)}
			{:else if entry && resource}
				{@render unavailable(entry, resource)}
			{:else}
				<hx-h1 id="res-title">Resource type not found</hx-h1>
				<hx-p class="ex-empty">{absence()}</hx-p>
			{/if}
		</hx-section>
	{/snippet}
</ExplorerFrame>

